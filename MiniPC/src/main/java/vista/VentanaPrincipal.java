        tblPrograma.getColumnModel().getColumn(0).setPreferredWidth(80);
        tblPrograma.getColumnModel().getColumn(1).setPreferredWidth(200);
        tblPrograma.getColumnModel().getColumn(2).setPreferredWidth(300);
        tblBCP.getColumnModel().getColumn(0).setPreferredWidth(80);
        tblBCP.getColumnModel().getColumn(1).setPreferredWidth(150);
        tblBCP.getColumnModel().getColumn(2).setPreferredWidth(150);
