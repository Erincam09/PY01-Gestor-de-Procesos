    private void btnCargarArchivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarArchivoActionPerformed
        JFileChooser selector = new JFileChooser();
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("Archivos ASM (*.asm)","asm");
        selector.setFileFilter(filtro);
        int resultado = selector.showOpenDialog(this);
        if (resultado == JFileChooser.APPROVE_OPTION) {
            File archivo = selector.getSelectedFile();
            try {
                controlador.cargarPrograma(archivo);
                actualizarVista();
                lblEstado.setText(
                        "Programa cargado: "
                        + archivo.getName()
                );
                btnSiguiente.setEnabled(true);
                btnEjecutarAutomatico.setEnabled(true);
                btnReiniciar.setEnabled(true);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this,e.getMessage(),"Error al cargar archivo",JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnCargarArchivoActionPerformed

